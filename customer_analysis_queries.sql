-- The company can also analyze why lower-cost shipping methods
-- are associated with smaller purchase amounts and explore upselling opportunities.

-- 7 Do subscribed customers spend more ? Compare average spend and total revenue between
-- subscribers and non-subscribers.

SELECT 
    subscription_status,
    AVG(purchase_amount) AS avg_spend,
    SUM(purchase_amount) AS total_revenue
FROM customers
GROUP BY subscription_status;

-- Insight:
-- Subscribed customers spend significantly more on average (198.65)
-- compared to non-subscribers (122.31),
-- indicating stronger purchasing behavior among subscribers.

-- However, non-subscribers generated higher total revenue overall,
-- likely due to a larger number of non-subscriber customers in the dataset.

-- Recommendation:
-- The business should focus on converting more non-subscribers into subscribers,
-- as subscribers demonstrate higher spending potential per purchase.

-- Personalized membership benefits, loyalty programs, and exclusive offers
-- can help improve subscription adoption and long-term customer value.

#8. Top 5 products with highest discount usage %
SELECT 
    item_purchased,
    
    COUNT(
        CASE 
            WHEN discount_applied = 'Yes' THEN 1 
        END
    ) * 100.0 / COUNT(*) AS discount_usage_percentage
FROM customers
GROUP BY item_purchased
ORDER BY discount_usage_percentage DESC
LIMIT 5;

-- Insight:
-- Laptop and Phone showed the highest discount usage percentages,
-- indicating customers are more likely to purchase these products when discounts are offered.

-- Recommendation:
-- The business can use targeted discount campaigns for high-demand products
-- to further improve sales and customer engagement.

# 9 egment customer into new, returning and loyal based on their total number of previous purchase,
-- and show the count of each segment.

SELECT 
    CASE 
        WHEN previous_purchases <= 10 THEN 'New'
        WHEN previous_purchases <= 20 THEN 'Returning'
        ELSE 'Loyal'
    END AS customer_segment,
    COUNT(*) AS customer_count
FROM customers
GROUP BY customer_segment;

-- Insight:
-- Loyal customers form the largest customer segment,
-- indicating strong repeat purchasing behavior and customer retention.

-- Recommendation:
-- The business should continue rewarding loyal customers through loyalty programs
-- while encouraging new and returning customers to purchase more frequently.

#10 Are customers who are repeat buyers (more than 5 previous purchases) 
SELECT 
