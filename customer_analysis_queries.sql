#1 which category generates the highest revenue
SELECT 
    Category,
    SUM(purchase_amount) AS total_revenue
FROM customers
GROUP BY Category
ORDER BY total_revenue DESC
-- Insight:
-- Clothing is the top revenue-generating category,
-- suggesting it is the most profitable product segment.

# 2 Are discounts increasing the purchase value?
SElECT
	discount_applied,
    ROUND(AVG(purchase_amount)) AS avg_purchase,
    ROUND(SUM(purchase_amount)) AS total_purchase
    FROM customers
    GROUP BY discount_applied;
-- Insight:
-- Customers who received discounts had a higher average purchase value
-- (163) compared to customers without discounts (131),
-- indicating that discounts encourage customers to spend more per purchase.

-- However, the total revenue generated from discounted purchases
-- (321,960) was slightly lower than non-discounted purchases (328,615).

-- This suggests that while discounts improve customer spending behavior,
-- they may not significantly increase overall business revenue
-- and could potentially impact profitability.

# Recommendation
#The company should optimize discount strategies to improve profitability while maintaining higher customer spending.


