    COUNT(*) AS customer_count
FROM customers
WHERE previous_purchases > 5
GROUP BY subscription_status;

#11 what is the revenue contribution of each age group?
SELECT 
    CASE
        WHEN age BETWEEN 18 AND 25 THEN 'Young Adults'
        WHEN age BETWEEN 26 AND 40 THEN 'Adults'
        ELSE 'Seniors'
    END AS age_group,
    SUM(purchase_amount) AS total_revenue
FROM customers
GROUP BY age_group;

-- Insight:
-- Adult customers contributed the highest share of total revenue,
-- indicating they are the most valuable customer segment.

-- Recommendation:
-- The business should focus targeted marketing and personalized offers
-- on high-performing age groups to maximize revenue growth.