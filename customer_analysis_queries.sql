#4 Which customer used a discount but still spent more than the average purchase amount ? 
SELECT
	customer_id
    purchase_amount,
    discount_applied
FROM customers
WHERE discount_applied = 'yes'
AND purchase_amount > (
	SELECT AVG(purchase_amount)
    FROM customers
    );
    
-- Insight:
-- Several customers who received discounts still spent above the overall average purchase amount,
-- indicating that discounts may effectively encourage high-value purchases.

-- Recommendation:
-- The business can target similar high-spending customers with personalized discount campaigns
-- to maximize customer retention and revenue generation.

#5Which are the top/bottom 5 products with the highest average review rating.

SELECT
	item_purchased,
    AVG(review_rating) as avg_review
    FROM customers
GROUP BY item_purchased
ORDER BY avg_review
LIMIT 5;

-- Insight:
-- Laptop and Bag received comparatively higher average review ratings,
-- indicating better customer satisfaction for these products.

-- Phone received the lowest average rating among the listed products,
-- suggesting possible issues related to quality, pricing, or customer expectations.

-- Recommendation:
-- The business should further investigate customer feedback and reviews for Phone products
-- to identify pain points and improve customer satisfaction.

-- Products with higher ratings such as Laptop and Bag can be promoted more aggressively
-- in marketing campaigns to leverage positive customer perception.

#6Average purchase: Standard vs Express shipping
